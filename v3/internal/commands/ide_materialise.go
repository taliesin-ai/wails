// ideMaterialiseOptions describes one refresh of a persistent IDE project.
type ideMaterialiseOptions struct {
	// Source is the generated tree from a completed wake run. It is only read.
	Source string
	// Destination is the persistent project directory, such as .wails/ide/android.
	Destination string
	// Prepare adds platform inputs to the staged copy before it is published.
	Prepare func(staged string) error
}

// ideMaterialiseResult reports what a refresh did to an existing project.
type ideMaterialiseResult struct {
	Path string
	// UserModified is true when the existing project no longer matched the
	// snapshot recorded by the previous refresh.
	UserModified bool
	// Backup holds the previous project contents when UserModified is true.
	Backup string
}

// ideDigestSuffix names the file beside a persistent project that records the
// digest of the last generated snapshot. It lives outside the project so IDEs
// never see it.
const ideDigestSuffix = ".digest"

// materialiseIDEProject publishes a fresh copy of the generated tree at
// Destination. The copy is built in a sibling staging directory and swapped in
// with a rename, so an interrupted refresh never leaves a half-written project.
//
// When the existing Destination differs from the snapshot recorded by the
// previous refresh, the user's version is moved to a numbered .bak path before
// the new snapshot is published. IDE user state (xcuserdata, .idea,
// local.properties) is carried over in both cases.
func materialiseIDEProject(options ideMaterialiseOptions) (ideMaterialiseResult, error) {
	result := ideMaterialiseResult{Path: options.Destination}
	parent := filepath.Dir(options.Destination)
	if err := os.MkdirAll(parent, 0o755); err != nil {
		return result, err
	}
	staged, err := os.MkdirTemp(parent, "."+filepath.Base(options.Destination)+"-stage-*")
	if err != nil {
		return result, err
	}
	defer os.RemoveAll(staged)
	// MkdirTemp creates the stage 0700. The published project should be readable like any other.
	if err := os.Chmod(staged, 0o755); err != nil {
		return result, err
	}
	if err := copyManifestPath(options.Source, staged); err != nil {
		return result, fmt.Errorf("copy generated project: %w", err)
	}
	if err := preserveIDEUserState(options.Destination, staged); err != nil {
		return result, fmt.Errorf("preserve IDE user state: %w", err)
	}
	if options.Prepare != nil {
		if err := options.Prepare(staged); err != nil {
			return result, err
		}
	}
	digest, err := digestIDETree(staged)
	if err != nil {
		return result, err
	}
	digestPath := options.Destination + ideDigestSuffix
	recorded, err := readIDEDigest(digestPath)
	if err != nil {
		return result, err
	}
	if _, err := os.Lstat(options.Destination); err == nil {
		current, err := digestIDETree(options.Destination)
		if err != nil {
			return result, err
		}
		if recorded == "" || current != recorded {
			backup, err := nextIDEBackupPath(options.Destination)
			if err != nil {
				return result, err
			}
			if err := os.Rename(options.Destination, backup); err != nil {
				return result, fmt.Errorf("keep changed project at %s: %w", backup, err)
			}
			result.UserModified = true
			result.Backup = backup
		}
	} else if !errors.Is(err, fs.ErrNotExist) {
		return result, err
	}
	if err := replacePathTransactional(staged, options.Destination); err != nil {
		if result.Backup != "" {
			if restoreErr := os.Rename(result.Backup, options.Destination); restoreErr != nil {
				return result, errors.Join(err, fmt.Errorf("restore project from %s: %w", result.Backup, restoreErr))
			}
		}
		return result, err
	}
	if err := writeIDEDigest(digestPath, digest); err != nil {
		return result, err
	}
	return result, nil
}

// ideUserStateName reports whether a file or directory name is written by an
// IDE rather than generated by wails. Such entries are preserved on refresh
// and excluded from change detection.
func ideUserStateName(name string) bool {
	switch name {
	case "xcuserdata", ".idea", "local.properties":
		return true
	}
	return false
}

// ideExcluded reports whether a path relative to a project root is ignored by
// change detection. Build caches and IDE state never count as user edits.
func ideExcluded(rel string, isDir bool) bool {
	name := path.Base(rel)
	if ideUserStateName(name) {
		return true
	}
	switch name {
	case ".gradle", ".DS_Store":
		return true
	case "build":
		return isDir
	}
	return false
}

// preserveIDEUserState copies IDE user state from the existing project into
// the staged copy, unless the generated tree already provides that path.
func preserveIDEUserState(existing, staged string) error {
	if _, err := os.Lstat(existing); errors.Is(err, fs.ErrNotExist) {
		return nil
	} else if err != nil {
		return err
	}
	return filepath.WalkDir(existing, func(current string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if current == existing {
			return nil
		}
		rel, err := filepath.Rel(existing, current)
		if err != nil {
			return err
		}
		if ideUserStateName(entry.Name()) {
			target := filepath.Join(staged, rel)
			if _, statErr := os.Lstat(target); errors.Is(statErr, fs.ErrNotExist) {
				if err := copyManifestPath(current, target); err != nil {
					return err
				}
			} else if statErr != nil {
				return statErr
			}
			if entry.IsDir() {
				return filepath.SkipDir
			}
			return nil
		}
		if entry.IsDir() && (entry.Name() == "build" || entry.Name() == ".gradle") {
			return filepath.SkipDir
		}
		return nil
	})
}

// digestIDETree returns a stable digest of the change-relevant content of a
// project tree: names, file modes, file contents and symlink targets.
func digestIDETree(root string) (string, error) {
	hash := sha256.New()
	err := filepath.WalkDir(root, func(current string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(root, current)
		if err != nil {
			return err
		}
		if rel == "." {
			return nil
		}
		rel = filepath.ToSlash(rel)
		if ideExcluded(rel, entry.IsDir()) {
			if entry.IsDir() {
				return filepath.SkipDir
			}
			return nil
		}
		info, err := entry.Info()
		if err != nil {
			return err
		}
		switch {
		case info.IsDir():
			fmt.Fprintf(hash, "dir %s\n", rel)
		case info.Mode()&fs.ModeSymlink != 0:
			target, err := os.Readlink(current)
			if err != nil {
				return err
			}
			fmt.Fprintf(hash, "link %s %s\n", rel, target)
		case info.Mode().IsRegular():
			file, err := os.Open(current)
			if err != nil {
				return err
			}
			contents := sha256.New()
			_, copyErr := io.Copy(contents, file)
			closeErr := file.Close()
			if copyErr != nil {
				return copyErr
			}
			if closeErr != nil {
				return closeErr
			}
			fmt.Fprintf(hash, "file %s %o %x\n", rel, info.Mode().Perm(), contents.Sum(nil))
		default:
			return fmt.Errorf("unsupported file type in IDE project: %s", rel)
		}
		return nil
	})
	if err != nil {
		return "", err
	}
	return hex.EncodeToString(hash.Sum(nil)), nil
}

func readIDEDigest(digestPath string) (string, error) {
	data, err := os.ReadFile(digestPath)
	if errors.Is(err, fs.ErrNotExist) {
		return "", nil
	}
	if err != nil {
		return "", err
	}
	return strings.TrimSpace(string(data)), nil
}

func writeIDEDigest(digestPath, digest string) error {
	temporary := digestPath + ".tmp"
	if err := os.WriteFile(temporary, []byte(digest+"\n"), 0o644); err != nil {
		return err
	}
	return os.Rename(temporary, digestPath)
}

// nextIDEBackupPath returns the first unused path among dst.bak, dst.bak.1,
// dst.bak.2 and so on, so earlier backups are never overwritten.
func nextIDEBackupPath(destination string) (string, error) {
	candidate := destination + ".bak"
	for index := 1; ; index++ {
		_, err := os.Lstat(candidate)
		if errors.Is(err, fs.ErrNotExist) {
			return candidate, nil
		}
		if err != nil {
			return "", err
		}
		candidate = destination + ".bak." + strconv.Itoa(index)
	}
}

// ideRunOptions builds the wake plan that produces the inputs of an IDE
// project. Without a profile the plan targets goos/arch and uses the
// development configuration only when development is set. A profile selects
// its own targets, so the explicit target and development flag are dropped.
func ideRunOptions(ctx context.Context, loaded *manifest.Loaded, profile, goos, arch string, formats []string, development bool) (manifestRunOptions, error) {
	// The build verb matches the mobile dev path. An iOS app bundle is the
	// runnable output, not a package format, so "package" would also try IPA.
	options := manifestRunOptions{Context: ctx, Verb: "build", Loaded: loaded}
	if profile != "" {
		selected := false
		for _, target := range loaded.Config.Selected.Targets {
			if strings.HasPrefix(target.Target, goos+"/") {
				selected = true
				break
			}
		}
		if !selected {
			return options, fmt.Errorf("profile %q does not select an %s target", profile, goos)
		}
		return options, nil
	}
	loaded.Config.Selected = manifest.Profile{}
	options.TargetOS = goos
	options.TargetArch = arch
	options.Formats = formats
	options.Development = development
	return options, nil
}

// ideFindPackage returns the package step that produced the artifact for goos
// and format within a completed run.
func ideFindPackage(run manifestPipelineRun, goos, format string) (pipeline.PackageSpec, error) {
	for _, key := range run.Plan.Artifacts {
		node := run.Plan.Nodes[key]
		spec, ok := node.Spec.(pipeline.PackageSpec)
		if ok && spec.TargetOS == goos && node.Artifact.Format == format {
			return spec, nil
		}
	}
	return pipeline.PackageSpec{}, fmt.Errorf("build produced no %s %s artifact", goos, format)
}

// ideOpener performs the platform effects of opening an IDE. Tests inject
// fakes for every field.
type ideOpener struct {
	goos     string
	lookPath func(string) (string, error)
	stat     func(string) (fs.FileInfo, error)
	run      func(name string, args ...string) error
}

func openXcodeProject(opener ideOpener, project string) error {
	if opener.goos != "darwin" {
		return fmt.Errorf("opening Xcode requires macOS")
	}
	return opener.run("open", project)
}

// openAndroidStudio opens dir in Android Studio using the first launcher
// found. It reports false, with no error, when no launcher is installed.
func openAndroidStudio(opener ideOpener, dir string) (bool, error) {
	if _, err := opener.lookPath("studio"); err == nil {
		return true, opener.run("studio", dir)
	}
	switch opener.goos {
	case "darwin":
		if _, err := opener.stat("/Applications/Android Studio.app"); err == nil {
			return true, opener.run("open", "-a", "Android Studio", dir)
		}
	case "linux":
		if _, err := opener.lookPath("studio.sh"); err == nil {
			return true, opener.run("studio.sh", dir)
		}
	}
	return false, nil
}
